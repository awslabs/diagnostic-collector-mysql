class TestLogFileParserScanFiles(unittest.TestCase):
    """Test cases for LogFileParser file scanning functionality."""
    
    def setUp(self):
        """Set up test fixtures with a temporary directory."""
        self.temp_dir = tempfile.mkdtemp()
        self.parser = LogFileParser(self.temp_dir)
    
    def tearDown(self):
        """Clean up temporary directory."""
        import shutil
        shutil.rmtree(self.temp_dir, ignore_errors=True)
    
    def test_scan_empty_directory(self):
        """Test scanning an empty directory returns empty list."""
        result = self.parser.scan_log_files()
        self.assertEqual(result, [])
    
    def test_scan_nonexistent_directory(self):
        """Test scanning a non-existent directory returns empty list."""
        parser = LogFileParser('/nonexistent/path')
        result = parser.scan_log_files()
        self.assertEqual(result, [])
    
    def test_scan_finds_query_log_files(self):
        """
        Test that scan finds query log files matching the expected pattern.
        
        Parse query log files
        """
        # Create test log files
        test_files = [
            'GLOBAL_STATUS_20260218_143052.log',
            'REPLICATION_STATUS_20260218_143052.log',
            'AURORA_CLUSTER_STATUS_20260218_143052.log',
        ]
        for filename in test_files:
            Path(os.path.join(self.temp_dir, filename)).touch()
        
        result = self.parser.scan_log_files()
        
        self.assertEqual(len(result), 3)
        for filepath in result:
            self.assertTrue(os.path.basename(filepath) in test_files)
    
    def test_scan_excludes_main_execution_log(self):
        """
        Test that scan excludes the main execution log file.
        
        The main log (diagnostic_collector_mysql_YYYYMMDD_HHMMSS.log) should not be
        included in the query log files list.
        """
        # Create main log and query log
        Path(os.path.join(self.temp_dir, 'diagnostic_collector_mysql_20260218_143052.log')).touch()
        Path(os.path.join(self.temp_dir, 'GLOBAL_STATUS_20260218_143052.log')).touch()
        
        result = self.parser.scan_log_files()
        
        self.assertEqual(len(result), 1)
        self.assertIn('GLOBAL_STATUS', result[0])
    
    def test_scan_excludes_non_log_files(self):
        """Test that scan excludes files that don't match the log pattern."""
        # Create various files
        Path(os.path.join(self.temp_dir, 'GLOBAL_STATUS_20260218_143052.log')).touch()
        Path(os.path.join(self.temp_dir, 'report_20260218_143052.html')).touch()
        Path(os.path.join(self.temp_dir, 'readme.txt')).touch()
        Path(os.path.join(self.temp_dir, 'invalid.log')).touch()  # No timestamp
        
        result = self.parser.scan_log_files()
        
        self.assertEqual(len(result), 1)
        self.assertIn('GLOBAL_STATUS', result[0])
    
    def test_scan_returns_sorted_results(self):
        """Test that scan returns files in sorted order."""
        test_files = [
            'ZEBRA_QUERY_20260218_143052.log',
            'ALPHA_QUERY_20260218_143052.log',
            'MIDDLE_QUERY_20260218_143052.log',
        ]
        for filename in test_files:
            Path(os.path.join(self.temp_dir, filename)).touch()
        
        result = self.parser.scan_log_files()
        
        basenames = [os.path.basename(f) for f in result]
        self.assertEqual(basenames, sorted(basenames))


